"""Write DataFrames as booktabs LaTeX tables into the study's TABLE_DIR.

The emitter is hand-rolled rather than ``DataFrame.to_latex`` so the output
stays stable across pandas versions and fully under our control. Generated
files are ready for ``\\input`` from ``draft/`` chapters::

    \\input{../projects/<study>/result/tables/<name>.tex}

This module is deliberately self-contained (no sibling imports) so tests can
load it by file path without package machinery.
"""

import subprocess
import sys
from datetime import UTC, datetime
from pathlib import Path

_LATEX_SPECIALS = {
    "\\": r"\textbackslash{}",
    "&": r"\&",
    "%": r"\%",
    "$": r"\$",
    "#": r"\#",
    "_": r"\_",
    "{": r"\{",
    "}": r"\}",
    "~": r"\textasciitilde{}",
    "^": r"\textasciicircum{}",
}


def escape_latex(value) -> str:
    """Escape LaTeX special characters in ``value`` (converted to str)."""
    return "".join(_LATEX_SPECIALS.get(ch, ch) for ch in str(value))


def _short_commit(repo_root: Path) -> str:
    # Provenance is metadata, not data: degrade to "unknown" instead of
    # failing the table write (deliberate exception to the fail-explicit rule).
    try:
        return subprocess.run(
            ["git", "-C", str(repo_root), "rev-parse", "--short", "HEAD"],
            capture_output=True,
            text=True,
            check=True,
        ).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def write_latex_table(
    df,
    name: str,
    cfg,
    *,
    caption: str | None = None,
    label: str | None = None,
    index: bool = False,
    float_format=r"{:.3g}".format,
) -> Path:
    """Write ``df`` as ``TABLE_DIR/<name>.tex`` (booktabs) and return the path.

    ``name`` must be a bare stem (no directory, no extension). With a
    ``caption`` the tabular is wrapped in a ``table`` environment and ``label``
    defaults to ``tab:<name>``. ``index=True`` includes the index as leading
    column(s). Floats go through ``float_format`` before LaTeX escaping.
    """
    assert name and "/" not in name and "\\" not in name, (
        f"name must be a bare file stem without directories, got: {name!r}"
    )
    assert "." not in name, f"name must not contain an extension, got: {name!r}"

    frame = df.reset_index() if index else df
    assert len(frame.columns) > 0, "DataFrame has no columns to write"

    def fmt_cell(value) -> str:
        if isinstance(value, float):
            return escape_latex(float_format(value))
        return escape_latex(value)

    alignment = "".join("r" if dtype.kind in "iuf" else "l" for dtype in frame.dtypes)
    header = " & ".join(escape_latex(col) for col in frame.columns)
    body = [
        " & ".join(fmt_cell(value) for value in row) + r" \\"
        for row in frame.itertuples(index=False)
    ]

    script = Path(sys.argv[0]).resolve() if sys.argv and sys.argv[0] else "unknown"
    stamp = datetime.now(UTC).isoformat(timespec="seconds")
    commit = _short_commit(Path(cfg.REPO_ROOT))

    lines = [
        f"% Generated by {script} on {stamp}, commit {commit} -- do not edit by hand.",
    ]
    if caption is not None:
        label = label if label is not None else f"tab:{name}"
        lines += [
            r"\begin{table}[tbp]",
            r"\centering",
            rf"\caption{{{caption}}}",
            rf"\label{{{label}}}",
        ]
    lines += [rf"\begin{{tabular}}{{{alignment}}}", r"\toprule", header + r" \\", r"\midrule"]
    lines += body
    lines += [r"\bottomrule", r"\end{tabular}"]
    if caption is not None:
        lines += [r"\end{table}"]

    table_dir = Path(cfg.TABLE_DIR)
    table_dir.mkdir(parents=True, exist_ok=True)
    out = table_dir / f"{name}.tex"
    out.write_text("\n".join(lines) + "\n")
    return out
