"""Tests for write_latex_values in src/utils/tables.py using a throwaway fake config."""

import csv
import json
from types import SimpleNamespace

import numpy as np
import pytest


@pytest.fixture()
def fake_cfg(tmp_path, study_root):
    return SimpleNamespace(
        TABLE_DIR=tmp_path / "tables",
        STUDY_ROOT=study_root,
        REPO_ROOT=study_root.parents[1],
    )


def body(path):
    """The \\defvalue lines, without the generated header comment."""
    lines = path.read_text().splitlines()
    assert lines[0].startswith("% Generated by ") and "do not edit by hand" in lines[0]
    return lines[1:]


def rows(path):
    with path.with_suffix(".csv").open(newline="") as handle:
        return list(csv.reader(handle))


def test_writes_defvalue_lines_sorted_by_key(tables_mod, fake_cfg):
    out = tables_mod.write_latex_values(
        {"rmse": 0.41349, "n": 120, "site": "Bay_A & B"},
        "example-main",
        fake_cfg,
        formats={"rmse": "{:.2f}"},
    )

    assert out == fake_cfg.TABLE_DIR / "example-main.tex"
    assert body(out) == [
        r"\defvalue{example-main-n}{120}",
        r"\defvalue{example-main-rmse}{0.41}",
        r"\deftextvalue{example-main-site}{Bay\_A \& B}",
    ]


def test_csv_keeps_full_keys_and_raw_values(tables_mod, fake_cfg):
    out = tables_mod.write_latex_values(
        {"rmse": 0.41349, "n": 120, "mean": (1.5, 0.25), "site": "Bay A"},
        "example-raw",
        fake_cfg,
        default_format="{:.1f}",
    )

    assert rows(out) == [
        ["key", "value", "uncertainty"],
        ["example-raw-mean", "1.5", "0.25"],
        ["example-raw-n", "120", ""],
        ["example-raw-rmse", "0.41349", ""],
        ["example-raw-site", "Bay A", ""],
    ]


def test_uncertainty_tuple_uses_the_key_format(tables_mod, fake_cfg):
    out = tables_mod.write_latex_values(
        {"depth": (12.345, 0.678)}, "example-unc", fake_cfg, formats={"depth": "{:.1f}"}
    )

    assert body(out) == [r"\defvalue{example-unc-depth}{12.3 +- 0.7}"]


def test_numpy_scalars_and_scientific_formats(tables_mod, fake_cfg):
    out = tables_mod.write_latex_values(
        {"count": np.int64(7), "rate": np.float32(1.2e-5)},
        "example-np",
        fake_cfg,
        default_format="{:.2g}",
    )

    assert body(out) == [r"\defvalue{example-np-count}{7}", r"\defvalue{example-np-rate}{1.2e-05}"]


def test_writes_values_sidecar(tables_mod, fake_cfg):
    tables_mod.write_latex_values(
        {"a": 1},
        "example-side",
        fake_cfg,
        provenance={"reproducibility": "R3", "transcribed_from": "smith2024ocean, Table 2"},
    )

    sidecar = json.loads((fake_cfg.TABLE_DIR / "example-side.provenance.json").read_text())
    assert sidecar["kind"] == "values"
    assert sidecar["artifact"] == "example-side"
    assert set(sidecar["files"]) == {"example-side.tex", "example-side.csv"}
    assert sidecar["reproducibility"] == "R3"
    assert sidecar["transcribed_from"] == "smith2024ocean, Table 2"


@pytest.mark.parametrize(
    ("values", "kwargs", "message"),
    [
        ({}, {}, "non-empty"),
        ({"Bad_Key": 1}, {}, "value keys"),
        ({"a--b": 1}, {}, "value keys"),
        ({"a": 1, 2: 3}, {}, "value keys"),
        ({"flag": True}, {}, "must be an int"),
        ({"flag": np.bool_(True)}, {}, "must be an int"),
        ({"x": float("nan")}, {"default_format": "{:.2f}"}, "not finite"),
        ({"x": float("inf")}, {"default_format": "{:.2f}"}, "not finite"),
        ({"x": 0.5}, {}, "say how to round"),
        ({"x": 12345.6}, {"formats": {"x": "{:,.1f}"}}, "cannot typeset"),
        ({"x": 0.5}, {"formats": {"x": "{:.1%}"}}, "cannot typeset"),
        ({"x": 0.5}, {"formats": {"x": "{:.2q}"}}, "not usable"),
        ({"x": 1}, {"formats": {"y": "{:.1f}"}}, "not in values"),
        ({"x": (1.0, 2.0, 3.0)}, {"default_format": "{:.1f}"}, "uncertainty"),
        ({"x": (1.0, -0.1)}, {"default_format": "{:.1f}"}, "negative"),
        ({"x": ""}, {}, "empty"),
        ({"x": "two\nlines"}, {}, "single line"),
        ({"x": [1, 2]}, {}, "must be an int"),
    ],
)
def test_rejects_bad_values(tables_mod, fake_cfg, values, kwargs, message):
    with pytest.raises(AssertionError, match=message):
        tables_mod.write_latex_values(values, "example-bad", fake_cfg, **kwargs)
    assert not (fake_cfg.TABLE_DIR / "example-bad.tex").exists()


@pytest.mark.parametrize("name", ["", "sub/x", "x.tex", "Example", "a b", "x%y"])
def test_rejects_bad_names(tables_mod, fake_cfg, name):
    with pytest.raises(AssertionError):
        tables_mod.write_latex_values({"a": 1}, name, fake_cfg)
