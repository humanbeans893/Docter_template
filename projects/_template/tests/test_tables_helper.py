def test_caption_is_latex_and_refuses_unescaped_specials(tables_mod, fake_cfg):
    df = pd.DataFrame({"x": [1]})
    for caption in ("95% CI", "A & B", "run #3"):
        with pytest.raises(AssertionError, match="unescaped"):
            tables_mod.write_latex_table(df, "example-caption", fake_cfg, caption=caption)
    assert not fake_cfg.TABLE_DIR.exists()

    caption = r"95\% CI of $\bar{x}$, A \& B"
    out = tables_mod.write_latex_table(df, "example-caption", fake_cfg, caption=caption)
    assert rf"\caption{{{caption}}}" in out.read_text()
    escaped = tables_mod.escape_latex("95% CI")
    out = tables_mod.write_latex_table(df, "example-caption", fake_cfg, caption=escaped)
    assert r"\caption{95\% CI}" in out.read_text()


def test_sources_records_the_files_a_table_was_built_from(tables_mod, tmp_path):
    # A promotion script in scripts/ names the CSVs it read, so make check can follow
    # them back to the experiment that wrote them.
    study = tmp_path / "projects" / "demo"
    csv_path = study / "result" / "tables" / "demo-fit.csv"
    csv_path.parent.mkdir(parents=True)
    csv_path.write_text("x,y\n1,2\n")
    processed = study / "data" / "processed" / "002_fit" / "series.csv"
    processed.parent.mkdir(parents=True)
    processed.write_text("t,v\n0,1\n")
    cfg = SimpleNamespace(TABLE_DIR=csv_path.parent, STUDY_ROOT=study, REPO_ROOT=tmp_path)
    given = {"path": "projects/demo/data/raw/legacy/a.csv", "sha256": "a" * 64}

    tables_mod.write_latex_table(
        pd.DataFrame({"x": [1]}),
        "demo-summary",
        cfg,
        sources=[csv_path, str(processed)],
        provenance={"sources": [given]},
    )
    tables_mod.write_latex_values({"n": 1}, "demo-values", cfg, sources=[csv_path])

    def recorded(name):
        return json.loads((cfg.TABLE_DIR / f"{name}.provenance.json").read_text())["sources"]

    digest = hashlib.sha256(b"x,y\n1,2\n").hexdigest()
    assert recorded("demo-summary") == [
        given,
        {"path": "projects/demo/result/tables/demo-fit.csv", "sha256": digest},
        {
            "path": "projects/demo/data/processed/002_fit/series.csv",
            "sha256": hashlib.sha256(b"t,v\n0,1\n").hexdigest(),
        },
    ]
    assert recorded("demo-values") == [
        {"path": "projects/demo/result/tables/demo-fit.csv", "sha256": digest}
    ]
    with pytest.raises(AssertionError, match="does not exist"):
        tables_mod.write_latex_values({"n": 1}, "demo-missing", cfg, sources=[tmp_path / "no"])
    with pytest.raises(AssertionError, match="list of paths"):
        tables_mod.write_latex_values({"n": 1}, "demo-missing", cfg, sources=csv_path)
    assert not (cfg.TABLE_DIR / "demo-missing.tex").exists()


def test_generated_files_carry_no_time_and_no_commit(tables_mod, fake_cfg, monkeypatch):
    def run_at(commit, created):
        monkeypatch.setattr(
            tables_mod, "_git_state", lambda cfg: {"git_commit": commit, "git_dirty": False}
        )
        monkeypatch.setattr(
            tables_mod,
            "datetime",
            SimpleNamespace(now=lambda tz: SimpleNamespace(isoformat=lambda timespec: created)),
        )

    run_at("aaaaaaa", "2026-01-01T00:00:00+00:00")
    tables_mod.write_latex_values({"rmse": 0.5}, "example-same", fake_cfg, default_format="{:.2f}")
    tables_mod.write_latex_table(pd.DataFrame({"x": [1.5]}), "example-table", fake_cfg)
    first = {path.name: path.read_bytes() for path in fake_cfg.TABLE_DIR.iterdir()}
    sidecar = json.loads(first["example-same.provenance.json"])

    later = "2099-01-01T00:00:00+00:00"
    run_at("fffffff", later)
    tables_mod.write_latex_values({"rmse": 0.5}, "example-same", fake_cfg, default_format="{:.2f}")
    tables_mod.write_latex_table(pd.DataFrame({"x": [1.5]}), "example-table", fake_cfg)
    second = {path.name: path.read_bytes() for path in fake_cfg.TABLE_DIR.iterdir()}

    data = sorted(name for name in first if not name.endswith(".provenance.json"))
    assert data == [
        "example-same.csv",
        "example-same.tex",
        "example-table.csv",
        "example-table.tex",
    ]
    assert {name: second[name] for name in data} == {name: first[name] for name in data}
    header = first["example-same.tex"].decode().splitlines()[0]
    assert header == f"% Generated by {sidecar['script']} -- do not edit by hand."
    assert sidecar["created"] not in header and sidecar["git_commit"] not in header
    again = json.loads(second["example-same.provenance.json"])
    assert (again["created"], again["git_commit"]) == (later, "fffffff")
    assert again["files"] == sidecar["files"]


# --- git state: only code counts, and the run is credited to the commit it started from ---

GIT_ID = ["-c", "user.name=t", "-c", "user.email=t@example.invalid", "-c", "commit.gpgsign=false"]


def git(repo: Path, *args: str) -> str:
    done = subprocess.run(
        ["git", "-C", str(repo), *GIT_ID, *args], check=True, capture_output=True, text=True
    )
    return done.stdout


def make_repo(root: Path, studies=("demo", "other")) -> Path:
    """A committed repository laid out like this one, with code and prose in every study."""
    files = {
        "config.py": "X = 1\n",
        "pyproject.toml": "[project]\n",
        "uv.lock": "version = 1\n",
        "STATE.md": "state\n",
        "draft/chapters/ch.tex": "text\n",
        "docs/notes.md": "notes\n",
    }
    for study in studies:
        files |= {
            f"projects/{study}/config.py": "Y = 1\n",
            f"projects/{study}/README.md": "readme\n",
            f"projects/{study}/src/analysis.py": "x = 1\n",
            f"projects/{study}/scripts/promote.py": "y = 1\n",
            f"projects/{study}/experiments/001_first/run.py": "z = 1\n",
            f"projects/{study}/experiments/001_first/README.md": "notes\n",
            f"projects/{study}/experiments/001_first/summary.md": "card\n",
            f"projects/{study}/experiments/EXP_SUMMARY.md": "index\n",
            f"projects/{study}/result/tables/.gitkeep": "",
        }
    for name, text in files.items():
        (root / name).parent.mkdir(parents=True, exist_ok=True)
        (root / name).write_text(text)
    git(root, "init", "-q")
    git(root, "add", ".")
    git(root, "commit", "-qm", "initial")
    return root


def cfg_for(repo: Path, study: str = "demo") -> SimpleNamespace:
    root = repo / "projects" / study
    return SimpleNamespace(TABLE_DIR=root / "result" / "tables", STUDY_ROOT=root, REPO_ROOT=repo)


def recorded(cfg, name: str) -> tuple:
    sidecar = json.loads((cfg.TABLE_DIR / f"{name}.provenance.json").read_text())
    header = (cfg.TABLE_DIR / f"{name}.tex").read_text().splitlines()[0]
    return (
        sidecar["git_commit"],
        sidecar["git_dirty"],
        header.endswith("-dirty -- do not edit by hand."),
    )


def head(repo: Path) -> str:
    return git(repo, "rev-parse", "--short", "HEAD").strip()


@needs_git
def test_regenerating_studies_one_after_another_stays_clean(tables_mod, tmp_path):
    repo = make_repo(tmp_path)
    demo, other = cfg_for(repo, "demo"), cfg_for(repo, "other")

    tables_mod.write_latex_values({"a": 1}, "demo-first", demo)
    tables_mod.write_latex_values({"b": 2}, "demo-second", demo)  # demo-first is untracked now
    tables_mod.write_latex_values({"c": 3}, "other-first", other)  # demo's result/ changed
    assert recorded(demo, "demo-second") == (head(repo), False, False)
    assert recorded(other, "other-first") == (head(repo), False, False)

    git(repo, "add", ".")
    git(repo, "commit", "-qm", "results")
    tables_mod.write_latex_values({"a": 10}, "demo-first", demo)  # a tracked result changes
    tables_mod.write_latex_values({"c": 30}, "other-first", other)
    assert recorded(other, "other-first") == (head(repo), False, False)


