def test_write_latex_table_emits_booktabs_with_escaping(tables_mod, fake_cfg):
    df = pd.DataFrame({"site_name": ["A_1", "B%"], "value": [1.23456, 2.0]})

    out = tables_mod.write_latex_table(
        df, "example-summary", fake_cfg, caption="Example summary", label="tab:example"
    )

    text = out.read_text()
    assert out == fake_cfg.TABLE_DIR / "example-summary.tex"
    assert "\\toprule" in text and "\\midrule" in text and "\\bottomrule" in text
    assert r"site\_name" in text and r"A\_1" in text and r"B\%" in text
    assert "\\caption{Example summary}" in text and "\\label{tab:example}" in text
    assert "1.23" in text  # float_format applied ({:.3g})
    assert text.startswith("% Generated by ") and "do not edit by hand" in text


def test_write_latex_table_writes_raw_numbers_as_csv(tables_mod, fake_cfg):
    df = pd.DataFrame({"site": ["A", "B"], "value": [1.23456, 2.0]}).set_index("site")

    out = tables_mod.write_latex_table(df, "example-csv", fake_cfg, index=True)

    csv_path = out.with_suffix(".csv")
    back = pd.read_csv(csv_path)
    assert list(back.columns) == ["site", "value"]
    assert back["value"].tolist() == [1.23456, 2.0]  # unrounded, unlike the .tex


def test_write_latex_table_writes_provenance_sidecar(tables_mod, fake_cfg):
    df = pd.DataFrame({"x": [1]})

    out = tables_mod.write_latex_table(
        df, "example-prov", fake_cfg, provenance={"reproducibility": "R2", "note": "from CSV"}
    )

    sidecar = json.loads((fake_cfg.TABLE_DIR / "example-prov.provenance.json").read_text())
    assert sidecar["artifact"] == "example-prov"
    assert sidecar["kind"] == "table"
    assert sidecar["experiment"] is None
    assert sidecar["reproducibility"] == "R2"
    assert sidecar["files"] == {
        name: hashlib.sha256((fake_cfg.TABLE_DIR / name).read_bytes()).hexdigest()
        for name in ("example-prov.tex", "example-prov.csv")
    }
    assert out.exists()


