@needs_git
def test_regeneration_check_in_the_docs_passes_when_nothing_changed(tables_mod, tmp_path):
    # The documented check after rerunning every generator: only the sidecars
    # (*.provenance.json: time and commit) may change, and they are excluded.
    repo = make_repo(tmp_path)
    demo = cfg_for(repo)
    df = pd.DataFrame({"site": ["A"], "rmse": [0.41349]})

    def regenerate(rmse=0.41349):
        tables_mod.write_latex_values({"rmse": rmse}, "demo-main", demo, default_format="{:.2f}")
        tables_mod.write_latex_table(df.assign(rmse=[rmse]), "demo-summary", demo)

    def check() -> str:
        return git(
            repo,
            "status",
            "--porcelain",
            "--",
            "projects/*/result/*",
            ":(exclude)*.provenance.json",
        )

    regenerate()
    git(repo, "add", ".")
    git(repo, "commit", "-qm", "results")
    regenerate()
    sidecars = git(repo, "status", "--porcelain", "--", "projects/*/result/*")
    assert "demo-main.provenance.json" in sidecars  # a new git_commit (and time)
    assert check() == ""
    regenerate(rmse=0.5)
    assert "demo-main.tex" in check() and "demo-summary.csv" in check()


def install_helper(repo: Path) -> Path:
    """Commit tables.py (and the experiment.py it loads) into ``repo``'s demo study."""
    target = repo / "projects" / "demo" / "src" / "utils" / "tables.py"
    target.parent.mkdir(parents=True, exist_ok=True)
    for name in ("tables.py", "experiment.py"):
        source = Path(__file__).resolve().parents[1] / "src" / "utils" / name
        shutil.copyfile(source, target.with_name(name))
    git(repo, "add", ".")
    git(repo, "commit", "-qm", "helpers")
    return target


@needs_git
def test_a_commit_during_the_run_credits_the_start_commit(tmp_path, load_module_by_path, capsys):
    repo = make_repo(tmp_path)
    module = load_module_by_path(install_helper(repo), f"{tmp_path.name}_tables_run")
    start = head(repo)
    assert module.GIT_AT_START == {"git_commit": start, "git_dirty": False}
    demo = cfg_for(repo)

    (repo / "draft" / "chapters" / "ch.tex").write_text("written during the run\n")
    git(repo, "commit", "-qam", "prose only")
    module.write_latex_values({"a": 1}, "demo-prose", demo)
    assert recorded(demo, "demo-prose") == (start, False, False)
    assert "changed during the run" not in capsys.readouterr().err

    (repo / "projects" / "demo" / "src" / "analysis.py").write_text("x = 2\n")
    git(repo, "commit", "-qam", "switch the estimator")
    module.write_latex_values({"a": 1}, "demo-code", demo)
    assert recorded(demo, "demo-code") == (start, True, True)
    assert "the code changed during the run" in capsys.readouterr().err


@needs_git
def test_a_run_started_from_uncommitted_code_stays_dirty_after_a_commit(
    tmp_path, load_module_by_path, capsys
):
    repo = make_repo(tmp_path)
    target = install_helper(repo)
    (repo / "projects" / "demo" / "src" / "analysis.py").write_text("x = 2\n")
    module = load_module_by_path(target, f"{tmp_path.name}_tables_dirty_start")
    start = head(repo)
    assert module.GIT_AT_START == {"git_commit": start, "git_dirty": True}
    demo = cfg_for(repo)

    module.write_latex_values({"a": 1}, "demo-dirty", demo)
    assert recorded(demo, "demo-dirty") == (start, True, True)
    assert "started from uncommitted code (projects/demo/src/analysis.py)" in (
        capsys.readouterr().err
    )

    git(repo, "commit", "-qam", "commit the edit mid-run")
    module.write_latex_values({"a": 1}, "demo-committed", demo)
    assert recorded(demo, "demo-committed") == (start, True, True)
